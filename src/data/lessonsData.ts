export const getLessonDocId = (level: string, week: number, order: number) => {
  return `${level.toLowerCase()}_w${week}_o${order}`;
};

export const STANDARD_LESSON_IDS = new Set<string>(
  SAMPLE_LESSONS.map((l) => getLessonDocId(l.level, l.week, l.order))
);

export const isStandardLessonDocId = (docId: string): boolean => {
  return STANDARD_LESSON_IDS.has(docId);
};
